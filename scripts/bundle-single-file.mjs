#!/usr/bin/env node
/**
 * Bundle the multi-file extension into a **single-file** version (dist/pi-sysmon.ts).
 *
 * Why a single file?
 *   pi's auto-discovery loads **every .ts file** under <configDir>/extensions/
 *   as an extension. So:
 *     · the multi-file version must live in a subdirectory
 *       (extensions/pi-sysmon/index.ts + sibling files)
 *     · laying several .ts files flat makes pi load braille.ts as an extension
 *       too, failing with "Extension does not export a valid factory function"
 *       and **refusing to start**
 *   The single-file version has no such constraint: just drop it at
 *   extensions/pi-sysmon.ts.
 *
 * This script only does "concatenate + dedupe imports + rename conflicts";
 * it introduces no dependencies.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const OUT_DIR = join(ROOT, "dist");
const OUT_FILE = join(OUT_DIR, "pi-sysmon.ts");

/** Concatenation order matters: depended-upon modules come first. */
const MODULES = [
	{ file: "metrics.ts", banner: "Metrics collection: read /proc for CPU/memory/network/disk" },
	{ file: "braille.ts", banner: "Braille 2x4 sub-pixel line-chart rendering" },
	{ file: "chart-panel.ts", banner: "Chart panel with axes / ticks / time labels" },
	// tokens.ts must come before blocks.ts: blocks.ts's Tokens block uses its `fmtTps`.
	// (Function declarations are hoisted, but placing it before its dependents reads
	//  better and avoids a TDZ trap if anyone adds a top-level `const` here later.)
	{ file: "tokens.ts", banner: "LLM token throughput (TPS) estimation and per-second bucket metering" },
	{ file: "blocks.ts", banner: "Metric block construction: history + snapshot → MetricBlock[]" },
	// state.ts before index.ts: the enablement precedence rules it owns are
	// consumed by index.ts's session_start / command handling.
	{ file: "state.ts", banner: "Enablement precedence: session choice vs global default" },
	{ file: "index.ts", banner: "pi extension main body" },
];

/**
 * Symbols to rename: avoid same-named declarations from different modules
 * colliding after concatenation.
 *
 * Currently **no renames are needed** — index.ts no longer carries its own
 * `renderPanel` (it imports from chart-panel.ts instead), and no two modules
 * share a name. The array is kept because it's the anti-collision mechanism:
 * when a name collision shows up in the future, add an entry here.
 */
const RENAMES = [];

const HEADER = `/**
 * pi-sysmon — bottom-style braille line charts in pi (CPU / memory / network).
 *
 * ⚠️ This file is auto-generated by scripts/bundle-single-file.mjs — do not edit directly.
 *    To change the code, edit the sources under src/ and run \`npm run build:single\`.
 *
 * Install (single-file form):
 *   Copy this file to <configDir>/extensions/pi-sysmon.ts
 *   i.e. ~/.pi/agent/extensions/pi-sysmon.ts (default configDir)
 *
 * Commands:
 *   /sysmon                  toggle on / off (this session only)
 *   /sysmon global on|off    default on/off for new sessions (applies to this one too)
 *   /sysmon chart            chart mode (default)
 *   /sysmon line             one-line text mode
 *   /sysmon footer           replace the entire bottom bar with charts
 *   /sysmon on|off           explicitly enable / disable (this session only)
 *
 * State:
 *   <configDir>/pi-sysmon.json holds the display preferences (mode / placement) and the
 *   global on/off default (\`/sysmon global on|off\`); the per-session on/off choice is a
 *   session entry written by \`/sysmon on|off\`, so it survives \`/resume\` of that session
 *   without affecting any other.
 *
 * Environment variables:
 *   PI_SYSMON_INTERVAL=1000      sampling interval in ms (floor 500)
 *   PI_SYSMON_POINTS=400         history point count (default adapts to terminal width)
 *   PI_SYSMON_CHART_HEIGHT=4     plot rows per chart (excluding the 4 border rows)
 *   PI_SYSMON_LABEL=title        readout position: title (default, border title bar) / box (floating box top-right) / both / none
 *   PI_SYSMON_DISKS=1            add an extra disk I/O chart
 *   PI_SYSMON_MODE=chart         initial mode
 */

import { execFileSync, spawn } from "node:child_process";
import type { Readable } from "node:stream";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import os, { homedir } from "node:os";
import { dirname, join } from "node:path";
import type { ExtensionAPI, ExtensionCommandContext } from "@earendil-works/pi-coding-agent";
import { truncateToWidth, visibleWidth } from "@earendil-works/pi-tui";
`;

/** Strip import lines and the `export` keyword; `export default` is kept (the extension entry needs it). */
function stripModuleSyntax(src) {
	let out = src;
	// Remove all import declarations (including multi-line `import type {\n...\n} from "..."`)
	out = out.replace(/^import[\s\S]*?from\s+"[^"]+";[ \t]*$/gm, "");
	// export default must be kept
	out = out.replace(/^export default\b/gm, "@@KEEP_DEFAULT@@");
	// Strip other export prefixes (after concatenation everything shares one module scope)
	out = out.replace(
		/^export (interface|type|function|const|let|class|enum|async)\b/gm,
		"$1",
	);
	// `export { ... }` re-export form (not present in this project; removed defensively)
	out = out.replace(/^export \{[\s\S]*?\};[ \t]*$/gm, "");
	out = out.replace(/@@KEEP_DEFAULT@@/g, "export default");
	return out.trim();
}

/**
 * Collect the **runtime symbol names** a source file imports from local modules
 * (excluding pure types).
 *
 * The single-file form concatenates all modules into one scope, so an "import"
 * in the output is just "the name being referenced directly". Once an imported
 * symbol has **no definition** in the output, runtime throws
 * `ReferenceError: xxx is not defined` — and this class of error is extremely
 * hard to catch during development: the code typechecks and unit tests pass
 * (tests import the source files directly and never go through bundling); it
 * only blows up when pi actually loads the extension. This self-check exists
 * to block exactly that kind of accident.
 */
function collectLocalImports(src) {
	const names = new Set();
	// Use `[^{}]*` instead of `[\s\S]*?`: the latter can **span across** multiple
	// import statements (it can eat `}` and the following `import`), mistaking
	// symbols from external packages for local imports.
	// An import specifier list can never contain nested braces, so `[^{}]*` is
	// both sufficient and can't overrun.
	const re = /import\s+(?:type\s+)?\{([^{}]*)\}\s*from\s*"\.\/[^"]+";/g;
	let m;
	while ((m = re.exec(src)) !== null) {
		const isTypeOnlyImport = /^\s*import\s+type\b/.test(m[0]);
		for (const raw of (m[1] ?? "").split(",")) {
			const t = raw.trim();
			if (!t) continue;
			// Skip inline `type X`: types produce no runtime code
			if (/^type\s/.test(t) || isTypeOnlyImport) continue;
			// `A as B` → take the original name A
			const name = t.replace(/\s+as\s+.*$/, "").trim();
			if (/^[A-Za-z_$][\w$]*$/.test(name)) names.add(name);
		}
	}
	return names;
}

/** Whether the symbol has a definition in the output (function/const/class/enum, with optional export prefix) */
function isDefinedIn(out, name) {
	const esc = name.replace(/[$]/g, "\\$");
	const re = new RegExp(
		`^(?:export\\s+)?(?:default\\s+)?(?:async\\s+)?(?:function|const|let|var|class|enum)\\s+${esc}\\b`,
		"m",
	);
	if (re.test(out)) return true;
	// Forms like `export { x }` / `export default function(){}` (defensive)
	if (new RegExp(`^export\\s*\\{[^}]*\\b${esc}\\b`, "m").test(out)) return true;
	return false;
}

/**
 * Collect the **top-level type names** a source file declares (interface / type / class / enum).
 *
 * The single-file form concatenates all modules into one scope, so two modules
 * declaring the same type name becomes
 * `ParseError: Identifier 'X' has already been declared` → **the extension
 * fails to load and pi reports an error**.
 * Typical scenario: module A defines and exports `type LabelMode`, and module B
 * copies another one for convenience.
 * Like "missing symbols", this class of error can't be caught by typecheck or
 * unit tests (they only look at sources / never go through bundling).
 *
 * Key point: **don't require `export`**. index.ts's `type LabelMode = ...`
 * has no export, and it was exactly the collision that really happened (my
 * first regex only matched `export type`, and the self-check still passed
 * after injecting a duplicate name).
 */
function collectTypeDecls(src) {
	const names = [];
	// Line start (allowing export before the indentation) counts as top-level, avoiding local types inside function bodies
	const re =
		/^(?:export\s+)?(?:declare\s+)?(?:interface|type|class|enum)\s+([A-Za-z_$][\w$]*)/gm;
	let m;
	while ((m = re.exec(src)) !== null) if (m[1]) names.push(m[1]);
	return names;
}

function main() {
	const chunks = [];
	for (const mod of MODULES) {
		const path = join(SRC, mod.file);
		if (!existsSync(path)) {
			console.error(`✗ missing source file: ${path}`);
			process.exit(1);
		}
		let code = stripModuleSyntax(readFileSync(path, "utf8"));
		for (const r of RENAMES) {
			if (r.in === mod.file) code = code.replace(r.from, r.to);
		}
		chunks.push(
			`// ══════════════════════════ ${mod.banner} ══════════════════════════\n\n${code}`,
		);
	}

	const out = `${HEADER}\n${chunks.join("\n\n")}\n`;

	// Self-check 1: no leftover local relative imports
	const localImport = /from\s+"\.\.?\//;
	if (localImport.test(out)) {
		console.error("✗ local relative imports remain in the bundle; the single-file version would fail to load:");
		for (const line of out.split("\n"))
			if (localImport.test(line)) console.error(`    ${line}`);
		process.exit(1);
	}

	// Self-check 2: every runtime symbol imported from local modules must be
	// defined in the output.
	// This is the only line of defense against ReferenceErrors that only blow up
	// when pi actually loads the extension (e.g. forgetting to add buildBlocks to
	// MODULES, or a rename in RENAMES producing a dangling name).
	const missing = [];
	for (const mod of MODULES) {
		const src = readFileSync(join(SRC, mod.file), "utf8");
		for (const name of collectLocalImports(src)) {
			if (!isDefinedIn(out, name)) missing.push(`${name} (imported by ${mod.file})`);
		}
	}
	if (missing.length > 0) {
		console.error(
			"✗ the following symbols are referenced but not defined in the bundle (runtime ReferenceError):",
		);
		for (const m of missing) console.error(`    ${m}`);
		console.error("  → if it's a new module, add it to MODULES; if it's a name collision, add it to RENAMES.");
		process.exit(1);
	}

	// Self-check 2b: every runtime symbol imported from EXTERNAL packages
	// (node:* builtins and npm deps) must be present in the HEADER's import
	// list — stripModuleSyntax removes all import lines and relies on the HEADER
	// to re-declare them. A missing one is the same ReferenceError class as
	// check 2, but sneakier: it only fails when the code path runs (the extension
	// loads fine, the value is just `undefined` until called). This exact bug
	// shipped once: `execFileSync` from node:child_process was stripped and the
	// macOS metrics silently degraded to zeros inside catch blocks.
	const headerImports = new Set();
	// Match BOTH forms: `import { a, b } from "x"` and `import def, { a } from "x"`
	// (the HEADER uses the latter for node:os). Both named specifier lists are
	// the same `[^{}]*` shape, so one regex with an optional default-binding
	// prefix covers them; bare `import x from` has no named list to check.
	for (const m of HEADER.matchAll(/import\s+(?:type\s+)?(?:[\w$]+\s*,\s*)?\{([^{}]*)\}\s+from\s+"[^"]+";/g)) {
		const isTypeOnlyImport = /^\s*import\s+type\b/.test(m[0]);
		if (isTypeOnlyImport) continue;
		for (const raw of (m[1] ?? "").split(",")) {
			const t = raw.trim();
			if (t && !/^type\s/.test(t)) headerImports.add(t.replace(/\s+as\s+.*$/, "").trim());
		}
	}
	// Also allow the sources' own `import os, { homedir }` mixed form to satisfy
	// the check when the HEADER imports the default binding of the same module.
	const headerDefaultBindings = new Set();
	for (const m of HEADER.matchAll(/import\s+([\w$]+)\s*(?:,|\{)/g)) headerDefaultBindings.add(m[1]);
	const missingExternal = [];
	for (const mod of MODULES) {
		const src = readFileSync(join(SRC, mod.file), "utf8");
		// external imports: not relative ("./x") — node builtins and npm packages alike.
		// Same mixed-form tolerance: `import os, { homedir } from "node:os"` must parse too.
		for (const m of src.matchAll(/import\s+(?:type\s+)?(?:[\w$]+\s*,\s*)?\{([^{}]*)\}\s+from\s+"(?!\.\/)[^"]+";/g)) {
			const isTypeOnlyImport = /^\s*import\s+type\b/.test(m[0]);
			if (isTypeOnlyImport) continue;
			for (const raw of (m[1] ?? "").split(",")) {
				const t = raw.trim();
				if (!t || /^type\s/.test(t)) continue;
				const name = t.replace(/\s+as\s+.*$/, "").trim();
				if (!/^[A-Za-z_$][\w$]*$/.test(name)) continue;
				// A named import is satisfied either by the HEADER's named list or by a
				// HEADER default binding of the same name (e.g. os's methods accessed as
				// `os.homedir()` would also work at runtime).
				if (!headerImports.has(name) && !headerDefaultBindings.has(name))
					missingExternal.push(`${name} (imported by ${mod.file} but absent from the HEADER import list)`);
			}
		}
	}
	if (missingExternal.length > 0) {
		console.error(
			"✗ the following external-package symbols are imported by sources but missing from the HEADER imports (runtime ReferenceError in the bundle):",
		);
		for (const m of missingExternal) console.error(`    ${m}`);
		console.error("  → add them to the HEADER's import list in this script.");
		process.exit(1);
	}

	// Self-check 3: the same type/interface/class name must not be declared in multiple modules.
	// The single-file form puts them all in one scope, so a duplicate name is a
	// `ParseError: Identifier 'X' has already been declared` (extension fails to load).
	const seen = new Map();
	const dups = [];
	for (const mod of MODULES) {
		const src = readFileSync(join(SRC, mod.file), "utf8");
		for (const name of collectTypeDecls(src)) {
			const prev = seen.get(name);
			if (prev) dups.push(`"${name}" declared in both ${prev} and ${mod.file}`);
			else seen.set(name, mod.file);
		}
	}
	if (dups.length > 0) {
		console.error("✗ the following type names are declared more than once (the single-file form would ParseError):");
		for (const d of dups) console.error(`    ${d}`);
		console.error("  → keep one as the single source of truth; change the other to import type.");
		process.exit(1);
	}

	mkdirSync(OUT_DIR, { recursive: true });
	writeFileSync(OUT_FILE, out, "utf8");

	const lines = out.split("\n").length;
	const bytes = Buffer.byteLength(out, "utf8");
	console.log(`✓ generated ${OUT_FILE}`);
	console.log(`  lines ${lines} / size ${(bytes / 1024).toFixed(1)} KB`);
	console.log("  local relative imports: 0 (self-contained)");
}

main();
